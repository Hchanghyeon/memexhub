// Writes the app's and the admin web's token code from design/tokens.json.
//   node design/build.mjs          write the files
//   node design/build.mjs --check  exit 1 if they are out of date (CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));
const HEAD = "Generated by design/build.mjs from design/tokens.json. Do not edit: change the JSON and run `npm run tokens`.";
const keys = (o) => Object.keys(o).filter((k) => !k.startsWith("$"));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const argb = (hex) => "0xFF" + hex.replace("#", "").toUpperCase();

function kotlin() {
  const c = keys(t.color);
  const colors = (mode) => c.map((k) => `    ${k} = Color(${argb(t.color[k][mode])}),`).join("\n");
  const num = (n) => (Number.isInteger(n) ? `${n}` : `${n}`);
  const type = keys(t.type).map((k) => {
    const s = t.type[k];
    return `    /** ${s.use} */\n    val ${k} = TextStyle(fontSize = ${s.size}.sp, lineHeight = ${s.line}.sp, fontWeight = FontWeight(${s.weight}), letterSpacing = ${s.tracking < 0 ? `(${s.tracking})` : s.tracking}.em)`;
  }).join("\n");
  const dps = (o) => keys(o).map((k) => `    val ${k} = ${o[k]}.dp`).join("\n");
  return `// ${HEAD}
package io.github.hchanghyeon.memexhub.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.em
import androidx.compose.ui.unit.sp

/** Every color the app uses. Screens read them through \`Mx.colors\`, never as literals. */
data class MxColors(
${c.map((k) => `    /** ${t.color[k].use} */\n    val ${k}: Color,`).join("\n")}
)

val MxLight = MxColors(
${colors("light")}
)

val MxDark = MxColors(
${colors("dark")}
)

object MxType {
${type}
}

object MxSpace {
${dps(t.space)}
}

object MxRadius {
${dps(t.radius)}
}

object MxLayout {
${dps(t.layout)}
}

object MxMotion {
${keys(t.motion).map((k) => `    const val ${k} = ${Number.isInteger(t.motion[k]) ? t.motion[k] : t.motion[k] + "f"}`).join("\n")}
}
`.replace(/\n{3,}/g, "\n\n");
}

function css() {
  const c = keys(t.color);
  const vars = (mode) => c.map((k) => `  --mx-${kebab(k)}: ${t.color[k][mode]};`).join("\n");
  const rest = [
    ...keys(t.type).flatMap((k) => [`  --mx-type-${k}-size: ${t.type[k].size}px;`, `  --mx-type-${k}-line: ${t.type[k].line}px;`, `  --mx-type-${k}-weight: ${t.type[k].weight};`, `  --mx-type-${k}-tracking: ${t.type[k].tracking}em;`]),
    ...keys(t.space).map((k) => `  --mx-space-${k}: ${t.space[k]}px;`),
    ...keys(t.radius).map((k) => `  --mx-radius-${k}: ${t.radius[k]}px;`),
    ...keys(t.layout).map((k) => `  --mx-layout-${kebab(k)}: ${t.layout[k]}px;`),
    `  --mx-motion-number: ${t.motion.numberMs}ms;`,
    `  --mx-motion-enter: ${t.motion.enterMs}ms;`,
  ].join("\n");
  return `/* ${HEAD} */
:root {
${vars("light")}
${rest}
}
.dark {
${vars("dark")}
}
`;
}

const outputs = {
  "android/app/src/main/kotlin/io/github/hchanghyeon/memexhub/ui/theme/Tokens.kt": kotlin(),
  "web/src/tokens.css": css(),
};
const check = process.argv.includes("--check");
let stale = 0;
for (const [rel, text] of Object.entries(outputs)) {
  const p = join(root, rel);
  const now = existsSync(p) ? readFileSync(p, "utf8") : "";
  if (now === text) continue;
  if (check) {
    console.error(`out of date: ${rel} (run npm run tokens)`);
    stale++;
  } else {
    writeFileSync(p, text);
    console.log(`wrote ${rel}`);
  }
}
process.exit(stale ? 1 : 0);
